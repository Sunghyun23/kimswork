"""Original beat-period table: labels stay compact on the MPC LCD."""
LABELS=['1 bar D','1 bar','1/2 D','1 bar T','1/2','1/4 D','1/2 T','1/4','1/8 D','1/4 T','1/8','1/16 D','1/8 T','1/16','1/16 T']
BEATS=[6,4,3,8/3,2,1.5,4/3,1,.75,2/3,.5,.375,1/3,.25,1/6]
LEGACY=[13,10,7,4,1]
KEYS=['Lfo1SyncDivision','MotionSyncDivision','Lfo2SyncDivision']
def append(params):
 import json
 from pathlib import Path
 p=Path(__file__).resolve().parents[1]
 for k,n in zip(KEYS,['LFO 1 Sync Rate','Motion Sync Rate','LFO 2 Sync Rate']):params.append(dict(key=k,name=n,choices=LABELS,default=7))
 d=json.loads((p/'dice-locks.json').read_text());lookup={v['key']:i for i,v in enumerate(params)}
 for k,owner in zip(KEYS,['LfoRateControl','ModRateControl','Lfo2RateControl']):d['targets'][str(lookup[k])]=d['locks'][owner]
 (p/'dice-locks.json').write_text(json.dumps(d,indent=2)+'\n')
 (p/'src/SyncGrid.h').write_text('// Generated by tools/sync_grid.py. One period in quarter-note beats.\n#pragma once\n#include <algorithm>\n#include <cmath>\nnamespace donut {\nstatic constexpr int kSyncCount=15;\nstatic constexpr float kSyncBeats[]={'+','.join(str(float(x))+'f'for x in BEATS)+'};\nstatic const char*const kSyncNames[]={'+','.join(json.dumps(x)for x in LABELS)+'};\nstatic constexpr int kLegacySyncIndex[]={13,10,7,4,1};\ninline int syncIndex(float cursor){return int(std::lround(std::clamp(cursor,0.f,1.f)*float(kSyncCount-1)));}\n}\n')
