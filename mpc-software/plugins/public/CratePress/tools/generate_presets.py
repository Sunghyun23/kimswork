#!/usr/bin/env python3
"""Generate complete native MPC program vectors from the reviewed bank."""
import json
from pathlib import Path
P=Path(__file__).resolve().parents[1]
bank=json.loads((P/'factory-presets.json').read_text())['presets']
assert len(bank)==32 and bank[0]['name']=='Init / Clean'
assert len({r['name'] for r in bank})==len(bank)
lines=['// Generated by tools/generate_presets.py. Edit factory-presets.json.']
for r in bank:
 lines.append('{ std::vector<float> v;v.reserve(LegacyCount);for(int i=0;i<LegacyCount;++i)v.push_back(param(i).def);')
 for key,value in r['values'].items():
  lines.append('v[%s]=%sf;'%(key,format(float(value),'.1f')))
 lines.append('addProgram(%s,v); }'%json.dumps(r['name']))
(P/'src/FactoryPrograms.inc').write_text('\n'.join(lines)+'\n')
print('Generated32 complete factory programs')
