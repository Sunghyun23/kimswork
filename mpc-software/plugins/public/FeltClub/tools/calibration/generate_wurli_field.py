#!/usr/bin/env python3
"""Original 2D constant-panel electrostatic boundary-element experiment.
No measured dimensions: normalized through-slot/reed/lead geometry hypotheses.
Produces coefficient data, not sampled audio or a claimed real-instrument FEM.
"""
from pathlib import Path
import argparse,json
import numpy as np

def panels(poly,step):
 p=np.asarray(poly,float);centres=[];tangents=[];lengths=[]
 for a,b in zip(p,np.roll(p,-1,axis=0)):
  length=np.linalg.norm(b-a);n=max(1,int(np.ceil(length/step)));delta=(b-a)/n
  for k in range(n):centres.append(a+(k+.5)*delta);tangents.append(delta/2);lengths.append(length/n)
 return np.array(centres),np.array(tangents),np.array(lengths)

def solve(z,step=1.,radius=64.,symmetric=False):
 # Steel reed has finite thickness; the bass solder mass extends beneath it.
 reed=[[-8,0],[8,0],[8,-3.5],[7,-3.5],[0,-8.5],[-7,-3.5],[-8,-3.5]]
 if symmetric:reed=[[-8,1.75],[8,1.75],[8,-1.75],[-8,-1.75]]
 reed=np.array(reed,float);reed[:,1]+=z
 plate_z=(-1.5,1.5) if symmetric else (-3,0)
 lo,hi=plate_z
 shapes=[(reed,0),([[-26,lo],[-9,lo],[-9,hi],[-26,hi]],1),([[9,lo],[26,lo],[26,hi],[9,hi]],1)]
 centre=[];tangent=[];length=[];potential=[];is_plate=[]
 for shape,v in shapes:
  c,t,l=panels(shape,step);centre.extend(c);tangent.extend(t);length.extend(l);potential.extend([v]*len(l));is_plate.extend([v==1]*len(l))
 angles=np.arange(96)*2*np.pi/96;circle=np.column_stack((np.cos(angles),np.sin(angles)))*radius;c,t,l=panels(circle,1e6)
 centre.extend(c);tangent.extend(t);length.extend(l);potential.extend([0]*len(l));is_plate.extend([False]*len(l))
 c=np.array(centre);t=np.array(tangent);l=np.array(length);n=len(c)
 # Four Gauss points integrate each panel's uniform line charge. Self term is
 # the analytic line integral; extra constant/zero-total-charge fix the 2D gauge.
 g,w=np.polynomial.legendre.leggauss(4);K=np.zeros((n,n))
 for point,weight in zip(g,w):
  d=c[:,None,:]-(c+t*point)[None,:,:];r=np.linalg.norm(d,axis=2);K+=weight*(-np.log(np.maximum(r,1e-15)))/(4*np.pi)
 np.fill_diagonal(K,(1-np.log(l/2))/(2*np.pi))
 A=np.empty((n+1,n+1));A[:n,:n]=K;A[n,:n]=1;A[:n,n]=1;A[n,n]=0
 rhs=np.r_[potential,0.];q=np.linalg.solve(A,rhs)
 residual=float(np.max(abs(np.sum(A*q[None,:],axis=1)-rhs)));charge=float(q[:n][np.array(is_plate)].sum())
 return charge,residual,n

def main():
 a=argparse.ArgumentParser();a.add_argument('--header',type=Path,required=True);a.add_argument('--report',type=Path,required=True);args=a.parse_args()
 z=np.arange(-36.,36.0001,.25);values=[];worst=0
 for i,x in enumerate(z):
  value,residual,n=solve(x);assert value>0 and np.isfinite(value) and residual<1e-8;values.append(value);worst=max(worst,residual)
  if i%40==0:print(f'field {i+1}/{len(z)}, {n}panels',flush=True)
 values=np.array(values);checks=[]
 for x in [-32.,-24.,-8.,-2.,0.,2.,8.,24.,32.]:
  normal=solve(x)[0];fine=solve(x,.65)[0];far=solve(x,1.,96.)[0];checks.append({'position':x,'base':normal,'fine':fine,'far':far,'mesh_relative':abs(fine-normal)/fine,'boundary_relative':abs(far-normal)/far})
 assert max(c['mesh_relative'] for c in checks)<.04
 base0=next(c['base'] for c in checks if c['position']==0);far0=next(c['far'] for c in checks if c['position']==0);dynamic_scale=max(abs(c['base']-base0) for c in checks)
 for c in checks:c['boundary_dynamic_relative']=abs((c['far']-far0)-(c['base']-base0))/dynamic_scale
 assert max(c['boundary_dynamic_relative'] for c in checks)<.02
 for x in [0.,2.,6.]:assert abs(solve(x,symmetric=True)[0]-solve(-x,symmetric=True)[0])<1e-8
 scale=float(values.max()-values.min());v=(values-values.min())/scale
 # Shape-preserving cubic Hermite derivatives; no interpolation overshoot.
 delta=np.diff(v)/.25;m=np.zeros(len(v));m[0]=delta[0];m[-1]=delta[-1]
 for k in range(1,len(v)-1):
  if delta[k-1]*delta[k]>0:m[k]=2*delta[k-1]*delta[k]/(delta[k-1]+delta[k])
 text='''#pragma once
#include <array>
namespace felt::wurli {
// Generated by tools/calibration/generate_wurli_field.py; normalized geometry,
// original electrostatic BEM coefficients, not measured/sampled instrument data.
inline constexpr float FieldMin=-36.f,FieldMax=36.f,FieldStep=.25f;
'''
 def literal(x):
  q=f'{x:.9g}';return q+('f' if '.' in q or 'e' in q else '.f')
 for name,xs in [('FieldCapacitance',v),('FieldSlope',m)]:text+=f'inline constexpr std::array<float,{len(xs)}> {name}{{{{\n'+',\n'.join(','.join(literal(x) for x in xs[i:i+8]) for i in range(0,len(xs),8))+'\n}};\n'
 text+='}\n'
 args.header.parent.mkdir(parents=True,exist_ok=True);args.header.write_text(text)
 report={'method':'2D constant charge panels, Gauss quadrature, Dirichlet conductors and enclosing ground; charge conservation gauge','geometry_units':'lateral slot clearance1; hypothesized ratios, not measured200A dimensions','reed':'steel rectangle and triangular solder below; opposite lead orientation mirrors position','positions':z.tolist(),'charge_per_unit_length_normalized':values.tolist(),'maximum_collocation_residual':worst,'checks':checks,'symmetric_geometry_even_charge_pass':True,'limits':'no 3D end effects, measured geometry or real-instrument fit; mesh/boundary tests are numerical only'}
 args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n');print('Field table and numerical convergence checks passed',flush=True)
if __name__=='__main__':main()
